// Setup page: shows the NextDNS hostnames for the profile, QR code, copy buttons, iOS profile download.
import * as Api from './api.js';
import { $ } from './utils.js';

const qrUrl = (data) =>
  `https://api.qrserver.com/v1/create-qr-code/?size=440x440&data=${encodeURIComponent(data)}&color=000000&bgcolor=ffffff`;

export function initSetup(profileId) {
  // NextDNS naming rules: DoT hostname = <id>.dns.nextdns.io, DoH = https://dns.nextdns.io/<id>
  const dotHost = `${profileId}.dns.nextdns.io`;
  const dohUrl  = `https://dns.nextdns.io/${profileId}`;

  $('profile-id-label').textContent = profileId;
  $('dash-profile').textContent = profileId;
  $('dot-host').textContent = dotHost;
  $('doh-url').textContent = dohUrl;
  showQr(qrUrl(dotHost), dotHost.toUpperCase());

  // Android / iOS toggle
  document.querySelectorAll('.mode-btn').forEach((btn) => {
    btn.addEventListener('click', () => {
      document.querySelectorAll('.mode-btn').forEach((b) => b.classList.remove('active'));
      document.querySelectorAll('.mode-panel').forEach((p) => p.classList.remove('active'));
      btn.classList.add('active');
      $('mode-' + btn.dataset.mode).classList.add('active');
      if (btn.dataset.mode === 'android') showQr(qrUrl(dotHost), dotHost.toUpperCase());
      else showQr(qrUrl(dohUrl), 'DOH URL FOR IOS PROFILE');
    });
  });

  wireCopy('copy-host', () => dotHost);
  wireCopy('copy-doh', () => dohUrl);

  // The .mobileconfig is generated by functions/mobileconfig.js (needs a real profile ID).
  $('download-profile').addEventListener('click', (e) => {
    if (Api.getMode() === 'demo') {
      e.preventDefault();
      alert('Demo mode: set NEXTDNS_PROFILE_ID in Cloudflare Pages to enable the profile download.');
    }
  });
}

function showQr(src, label) {
  $('qr-img').src = src;
  $('qr-label-text').textContent = label;
}

function wireCopy(buttonId, getValue) {
  const btn = $(buttonId);
  btn.addEventListener('click', () => {
    navigator.clipboard.writeText(getValue()).then(() => {
      const original = btn.textContent;
      btn.textContent = 'Copied';
      btn.classList.add('copied');
      setTimeout(() => { btn.textContent = original; btn.classList.remove('copied'); }, 1500);
    });
  });
}
